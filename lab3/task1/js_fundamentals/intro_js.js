//!3
// What in-browser JavaScript CAN do
// Manipulate the webpage (HTML, CSS, DOM)
// React to user actions (clicks, keyboard, mouse, touch)
// Send and receive data from servers (AJAX / fetch)
// Work with cookies and local storage
// Show messages, dialogs, and notifications
// Upload and download files with user interaction

//!4
// What in-browser JavaScript CANNOT do
// Access the operating system directly
// Read, write, or execute arbitrary files on the user’s computer
// Use camera or microphone without user permission
// Access data from other websites or browser tabs (Same Origin Policy)
// Read private data from other pages (e.g. Gmail)